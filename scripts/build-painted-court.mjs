// Standalone review page and the identical offline native WebView page.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const read = (path) => readFileSync(`${root}${path}`, 'utf8');
const asset = (name) => `data:image/png;base64,${readFileSync(`${root}assets/images/painted-court/${name}.png`).toString('base64')}`;
// This small canvas scene has one dependency: the existing pure ball-flight module.
const physics = read('web/lib/ballistics.js').replace(/^export /gm, '');
const game = read('web/painted-court.js');
const config = { background: asset('courtyard'), player: asset('forehand-poses') };
const script = `(()=>{const ART=${JSON.stringify(config)};\n${physics}\n${game}\n})();`.replace(/<\/script/gi, '<\\/script');
const html = read('web/painted-court.html').replace('<!-- COURTYARD_SCRIPT -->', `<script>${script}</script>`);
mkdirSync(`${root}dist/painted-court`, { recursive: true });
writeFileSync(`${root}dist/painted-court/index.html`, html);
writeFileSync(`${root}src/generated/painted-court-html.ts`, `// Generated by scripts/build-painted-court.mjs.\nexport const PAINTED_COURT_HTML = ${JSON.stringify(html)};\n`);
console.log(`Painted courtyard: ${(html.length / 1024 / 1024).toFixed(1)} MB, all artwork embedded for offline play.`);
