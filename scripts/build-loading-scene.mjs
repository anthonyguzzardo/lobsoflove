import { readFileSync, writeFileSync } from 'node:fs';
const root = new URL('../', import.meta.url);
const asset = path => 'data:image/png;base64,' + readFileSync(new URL(path, root)).toString('base64');
const html = readFileSync(new URL('web/loading-scene.html', root), 'utf8')
  .replace('__FRAMES__', JSON.stringify(asset('assets/images/lol-splash/loading-frames.png')))
  .replace('__CHALK__', JSON.stringify(asset('assets/images/lol-splash/chalk-halo.png')));
writeFileSync(new URL('src/generated/loading-scene-html.ts', root), '// Generated by scripts/build-loading-scene.mjs.\nexport const LOADING_SCENE_HTML = ' + JSON.stringify(html) + ';\n');
console.log('Bundled offline loading artwork.');
