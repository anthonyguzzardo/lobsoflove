import { readFileSync, writeFileSync } from 'node:fs';
const root = new URL('../', import.meta.url);
const drawing = readFileSync(new URL('web/love-intro.js', root), 'utf8');
const html = readFileSync(new URL('web/loading-scene.html', root), 'utf8').replace('__DRAWING__', () => drawing);
writeFileSync(new URL('src/generated/loading-scene-html.ts', root), '// Generated by scripts/build-loading-scene.mjs.\nexport const LOADING_SCENE_HTML = ' + JSON.stringify(html) + ';\n');
console.log('Bundled calm title entrance and optional full replay.');
